// Transform scripts/out/content.json + nav.json into typed, sanitized TypeScript
// modules under src/content/, plus a media manifest and a route manifest.
//
//   node scripts/extract-content.mjs
//   node scripts/generate-content.mjs
//
// Slugs are the real hierarchical WordPress permalinks (about/i-filosofia-mas).
// EN pages keep their own real slugs (about/our-philosophy) — no invented prefix.
// Pages without a WPML English version get Greek as an en fallback, enReviewed:false.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const OUT = join(__dirname, 'out')
const CONTENT = join(ROOT, 'src', 'content')

const groups = JSON.parse(readFileSync(join(OUT, 'content.json'), 'utf8'))
const nav = JSON.parse(readFileSync(join(OUT, 'nav.json'), 'utf8'))
const attachments = JSON.parse(readFileSync(join(OUT, 'attachments.json'), 'utf8'))
const usedMedia = new Set()

function decodeEntities(s) {
  return String(s || '')
    .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/&nbsp;/g, ' ').replace(/ageing/g, 'aging').replace(/Ageing/g, 'Aging')
    .replace(/&nbsp;/g, ' ')
}

function useUpload(path) {
  if (!path) return undefined
  usedMedia.add(path)
  return `/assets/uploads/${path}`
}

/** WPBakery + Mikado shortcode markup -> clean, allow-listed HTML. */
function clean(raw) {
  let s = String(raw || '')
  s = s.replace(/\[mkdf_section_title\b[^\]]*?\btext="([^"]*)"[^\]]*\]/g, (_, t) =>
    t.trim() ? `<h2>${decodeEntities(t)}</h2>` : '')
  s = s.replace(/\[(?:vc|mkdf)_single_image\b[^\]]*?\bimage="(\d+)"[^\]]*\]/g, (_, id) => {
    const p = attachments[id]
    const src = p ? useUpload(p) : null
    return src ? `<figure><img src="${src}" alt="" loading="lazy" /></figure>` : ''
  })
  s = s.replace(/\[\/?[a-z0-9_]+[^\]]*\]/gi, '')
  s = s.replace(/https?:\/\/(?:neo\.)?marathiatinos\.gr\/wp-content\/uploads\/([^\s"')]+)/g,
    (_, p) => useUpload(decodeURIComponent(p)) || '')
  // internal links -> local absolute paths (keep hierarchical path, drop host + trailing slash)
  s = s.replace(/https?:\/\/(?:neo\.)?marathiatinos\.gr\/([a-z0-9/-]+?)\/?(["'])/gi, '/$1$2')
  s = s.replace(/https?:\/\/(?:neo\.)?marathiatinos\.gr\/?/gi, '/')
  s = s.replace(/\s(?:style|class|id|data-[a-z-]+)="[^"]*"/gi, '')
  const allowed = new Set(['p', 'a', 'strong', 'b', 'em', 'i', 'u', 'ul', 'ol', 'li',
    'h2', 'h3', 'h4', 'br', 'blockquote', 'img', 'figure', 'figcaption', 'span'])
  s = s.replace(/<\/?([a-z0-9]+)([^>]*)>/gi, (m, tag) => allowed.has(tag.toLowerCase()) ? m : '')
  // drop leftover "Lorem ipsum" placeholder blocks (hidden on the live site via CSS)
  s = s.replace(/<(p|h2|h3|h4|li|blockquote)\b[^>]*>(?:(?!<\/\1>)[\s\S])*?lorem ipsum(?:(?!<\/\1>)[\s\S])*?<\/\1>/gi, '')
  s = s.replace(/<p>\s*(?:&nbsp;)?\s*<\/p>/gi, '')
    .replace(/<span>\s*<\/span>/gi, '')
  s = s.replace(/ageing/g, 'aging').replace(/Ageing/g, 'Aging')
    .replace(/[ \t]+\n/g, '\n').replace(/\n{3,}/g, '\n\n').replace(/\s{2,}/g, ' ').trim()
  return s
}

const esc = (s) => String(s ?? '').replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')
const q = (s) => JSON.stringify(s ?? '')
const fileKey = (s) => String(s || 'untitled').replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '').toLowerCase()
const localized = (el, en, hasEn) => ({ el, en: hasEn ? en : el })

mkdirSync(join(CONTENT, 'pages'), { recursive: true })

const pageFiles = [] // {key, file}
const postFiles = []
let homeFile = null
const dishes = []
const testimonials = []
const portfolio = []

for (const g of groups) {
  const hasEn = g.has_en
  if (g.type === 'home' || g.type === 'page' || g.type === 'post') {
    const isPost = g.type === 'post'
    const key = g.type === 'home' ? 'home' : (isPost ? 'post-' + g.slug_el : g.slug_el)
    const file = g.type === 'home' ? 'home' : fileKey(key)
    const bodyEl = clean(g.content_el)
    const bodyEn = clean(hasEn ? g.content_en : g.content_el)
    const hero = g.thumb_el ? useUpload(g.thumb_el) : undefined
    const descEl = (decodeEntities(g.excerpt_el) || bodyEl.replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim().slice(0, 155)
    const descEn = (decodeEntities(hasEn ? g.excerpt_en : g.excerpt_el) || bodyEn.replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim().slice(0, 155)
    const mod = `// AUTO-GENERATED by scripts/generate-content.mjs
import type { PageContent } from '@/types/content'

const content: PageContent = {
  key: ${q(key)},
  type: ${q(g.type)},
  slug: { el: ${q(g.slug_el)}, en: ${q(g.slug_en ?? g.slug_el)} },
  title: { el: ${q(decodeEntities(g.title_el))}, en: ${q(decodeEntities(hasEn ? g.title_en : g.title_el))} },${hero ? `
  hero: { image: ${q(hero)} },` : ''}${g.date ? `
  date: ${q(String(g.date))},` : ''}
  seo: {
    title: { el: ${q(decodeEntities(g.title_el))}, en: ${q(decodeEntities(hasEn ? g.title_en : g.title_el))} },
    description: { el: ${q(descEl)}, en: ${q(descEn)} },
  },
  enReviewed: ${hasEn ? 'true' : 'false'},
  body: {
    el: \`${esc(bodyEl)}\`,
    en: \`${esc(bodyEn)}\`,
  },
}

export default content
`
    writeFileSync(join(CONTENT, 'pages', `${file}.ts`), mod)
    if (g.type === 'home') homeFile = { key, file }
    else if (isPost) postFiles.push({ key, file })
    else pageFiles.push({ key, file })
  } else if (g.type === 'restaurant-menu') {
    dishes.push({
      key: fileKey(g.slug_el),
      slug: localized(g.slug_el, g.slug_en || g.slug_el, hasEn),
      title: localized(decodeEntities(g.title_el), decodeEntities(g.title_en), hasEn),
      body: { el: clean(g.content_el), en: clean(hasEn ? g.content_en : g.content_el) },
      image: g.thumb_el ? useUpload(g.thumb_el) : undefined,
      enReviewed: hasEn,
    })
  } else if (g.type === 'testimonials') {
    testimonials.push({
      key: fileKey(g.slug_el),
      title: localized(decodeEntities(g.title_el), decodeEntities(g.title_en), hasEn),
      body: { el: clean(g.content_el), en: clean(hasEn ? g.content_en : g.content_el) },
    })
  } else if (g.type === 'portfolio-item') {
    portfolio.push({
      key: fileKey(g.slug_el),
      title: localized(decodeEntities(g.title_el), decodeEntities(g.title_en), hasEn),
      image: g.thumb_el ? useUpload(g.thumb_el) : undefined,
      enReviewed: hasEn,
    })
  }
}

writeFileSync(join(CONTENT, 'menu.ts'),
  `// AUTO-GENERATED by scripts/generate-content.mjs\nimport type { MenuDish } from '@/types/content'\n\nconst menu: MenuDish[] = ${JSON.stringify(dishes, null, 2)}\n\nexport default menu\n`)
writeFileSync(join(CONTENT, 'testimonials.ts'),
  `// AUTO-GENERATED by scripts/generate-content.mjs\nimport type { Testimonial } from '@/types/content'\n\nconst testimonials: Testimonial[] = ${JSON.stringify(testimonials, null, 2)}\n\nexport default testimonials\n`)
writeFileSync(join(CONTENT, 'portfolio.ts'),
  `// AUTO-GENERATED by scripts/generate-content.mjs\nexport interface PortfolioItem { key: string; title: { el: string; en: string }; image?: string; enReviewed: boolean }\n\nconst portfolio: PortfolioItem[] = ${JSON.stringify(portfolio, null, 2)}\n\nexport default portfolio\n`)

// nav module
writeFileSync(join(CONTENT, 'nav.ts'),
  `// AUTO-GENERATED by scripts/generate-content.mjs — from the real WordPress "Kyrio menou" menu.\nexport interface NavItem { label: string; href: string | null; children?: NavItem[] }\nexport interface SiteNav { el: NavItem[]; en: NavItem[]; footer_el: NavItem[]; footer_en: NavItem[] }\n\nconst nav: SiteNav = ${JSON.stringify(nav, null, 2)}\n\nexport default nav\n`)

// registry
const id = (k) => '_' + k.replace(/[^a-z0-9]/gi, '_')
const allPageFiles = [...(homeFile ? [homeFile] : []), ...pageFiles]
const index = `// AUTO-GENERATED by scripts/generate-content.mjs
import type { PageContent } from '@/types/content'
${allPageFiles.map((f) => `import ${id(f.key)} from './pages/${f.file}'`).join('\n')}
${postFiles.map((f) => `import ${id(f.key)} from './pages/${f.file}'`).join('\n')}
export { default as menu } from './menu'
export { default as testimonials } from './testimonials'
export { default as portfolio } from './portfolio'
export { default as nav } from './nav'

export const home: PageContent${homeFile ? '' : ' | undefined'} = ${homeFile ? id(homeFile.key) : 'undefined'}

export const pages: PageContent[] = [
${pageFiles.map((f) => '  ' + id(f.key)).join(',\n')},
]

export const posts: PageContent[] = [
${postFiles.map((f) => '  ' + id(f.key)).join(',\n')},
]

export const allContent: PageContent[] = [${homeFile ? id(homeFile.key) + ', ' : ''}...pages, ...posts]

export function findBySlug(slug: string): PageContent | undefined {
  return allContent.find((p) => p.slug.el === slug || p.slug.en === slug)
}
`
writeFileSync(join(CONTENT, 'index.ts'), index)

writeFileSync(join(OUT, 'used-media.json'), JSON.stringify([...usedMedia].sort(), null, 2))

// route manifest — clean canonical URLs: el at the root slug, en prefixed with /en/.
// Bases come from the hand-authored src/site/canonical.json (keyed by content key =
// slug_el for pages, "home" for the front page); pages/posts missing an entry fall
// back to their WP el-slug. Keep this in sync with the router + navigation module.
const canonical = JSON.parse(readFileSync(join(ROOT, 'src', 'site', 'canonical.json'), 'utf8'))
const retired = JSON.parse(readFileSync(join(ROOT, 'src', 'site', 'retired.json'), 'utf8'))
const bothLocales = (elPath) => [elPath, elPath === '/' ? '/en' : '/en' + elPath]
const pageBase = (g) => canonical[g.slug_el] ?? g.slug_el

const routes = new Set(['/', '/en'])
for (const g of groups.filter((x) => x.type === 'page')) {
  if (retired[g.slug_el]) continue // retired page — only redirects, no canonical URL
  for (const p of bothLocales('/' + pageBase(g))) routes.add(p)
}
for (const g of groups.filter((x) => x.type === 'post')) {
  for (const p of bothLocales('/blog/' + g.slug_el)) routes.add(p)
}
for (const base of ['/blog', '/menu']) for (const p of bothLocales(base)) routes.add(p)
mkdirSync(join(ROOT, 'src', 'site'), { recursive: true })
writeFileSync(join(ROOT, 'src', 'site', 'routes.json'), JSON.stringify([...routes].sort(), null, 2))

console.log(`Generated: home=${Boolean(homeFile)}, ${pageFiles.length} pages, ${postFiles.length} posts, ${dishes.length} dishes, ${testimonials.length} testimonials, ${portfolio.length} portfolio.`)
console.log(`Referenced media: ${usedMedia.size}; routes: ${routes.size}`)
